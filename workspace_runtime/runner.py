RUN_ID = re.compile(r"[a-z0-9][a-z0-9_-]{0,79}\Z")


def read(p):
    return json.loads(p.read_text(encoding="utf-8"))


def save(p, obj):
    tmp = p.with_suffix(".tmp")
    tmp.write_text(json.dumps(obj, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    tmp.replace(p)


def project_path(user_path):
    p = user_path.resolve(strict=True)
    if not p.is_relative_to(ROOT):
        raise ValueError(f"Input must be inside this workspace: {p}")
    return p


def run_path(section, run_id):
    if not run_id or not RUN_ID.fullmatch(run_id):
        raise ValueError("Use --run-id with lowercase letters, digits, underscores or hyphens")
    anchor = SECTIONS[section] / "runs"
    out = anchor / run_id
    if anchor.resolve() != anchor or out.resolve() != out:
        raise ValueError("Run directory must not be a link")
    return out


@contextmanager
def writable_run(out, contract, resume):
    if resume:
        if not (out / "run.json").is_file() or read(out / "run.json") != contract:
            raise ValueError("Resume configuration/input/code changed or run ID is missing; choose a new run ID")
    else:
        out.mkdir(parents=True, exist_ok=False)
        with (out / "run.json").open("x", encoding="utf-8") as f:
            json.dump(contract, f, indent=2, ensure_ascii=False)
    lock = out / "workspace.lock"
    with lock.open("x", encoding="utf-8") as f:
        f.write(str(os.getpid()))
    try:
        yield
    finally:
        lock.unlink()


def code_record(section, engine=None):
    files = list(Path(__file__).parent.glob("*.py"))
    files.append(paths.PLAN)
    if section == 2:
        files.extend((SECTIONS[2] / "source").glob("*.py"))
    try:
        head = subprocess.check_output(
            ["git", "-c", f"safe.directory={REPO.as_posix()}", "-C", str(REPO), "rev-parse", "HEAD"],
            text=True, stderr=subprocess.DEVNULL).strip()
    except (OSError, subprocess.CalledProcessError):
        head = None
    record = dict(git_head=head, files={p.relative_to(ROOT).as_posix(): sha(p) for p in sorted(files)})
    if section in (3, 4) and engine != "periodic":
        bundle = CALIBRATED if engine == "cf_calibrated" else FULL
        record["release_manifest_sha256"] = sha(bundle / "bundle_manifest.json")
    return record


def parser(section):
    p = argparse.ArgumentParser(description=f"SFHFlow {section:02d}: versioned runs in this section's runs/ directory")
    p.add_argument("action", choices=("plan", "verify", "run", "prepare") if section == 3 else
                   ("plan", "verify", "run"))
    p.add_argument("--run-id")
    p.add_argument("--resume", action="store_true")
    p.add_argument("--device", choices=("cpu", "cuda"))
    p.add_argument("--smoke", action="store_true", help="diagnostic budget; cannot be promoted to a formal result")
    p.add_argument("--limit", type=int, help="max new steps or epochs in this invocation")
    p.add_argument("--q", type=int, default=217, help="CF heat flux in mW/cm²")
    if section in (2, 4):
        p.add_argument("--geometry", choices=("cf", "periodic"), default="cf")
        p.add_argument("--speed", type=float, default=4., help="periodic v_n in mm/s")
    if section == 2:
        p.add_argument("--fps", type=int)
        p.add_argument("--seed", type=int)
        p.add_argument("--frames", type=int)
    if section == 3:
        p.add_argument("--input", type=Path, help="real CF case directory generated by 02")
        p.add_argument("--profile", choices=("baseline_retrain_all", "continuation_short", "joint_continuation"),
                       default="baseline_retrain_all")
        p.add_argument("--field-budget", type=int, choices=(200,600), default=200)
    if section == 4:
        p.add_argument("--engine", choices=("auto", "cf", "cf_calibrated", "periodic"), default="auto")
        p.add_argument("--probability-run", help="03 run ID with a complete probability freeze")
        p.add_argument("--budget", type=int, choices=(200, 600), default=200)
        p.add_argument("--seed", type=int, choices=(301030, 301031, 301032), default=301030)
    return p


def prepare_args(section, args):
    if args.limit is not None and args.limit < 1:
        raise ValueError("--limit must be positive")
    if not 0 < args.q or not math.isfinite(getattr(args, "speed", 1.)):
        raise ValueError("Invalid physical case")
    if section == 4:
        if args.engine == "auto":
            args.engine = "periodic" if args.geometry == "periodic" else (
                "cf" if args.probability_run else "cf_calibrated")
        if args.engine == "cf_calibrated" and (args.q != 217 or args.budget != 200):
            raise ValueError("The published calibrated release is Q217/200 only; use --engine cf with a 03 run for other CF cases")
        if args.engine == "cf" and not args.probability_run:
            raise ValueError("Provide --probability-run for the channel PINN engine")
        if args.probability_run and args.engine != "cf":
            raise ValueError("--probability-run applies to the cf engine")
        if args.engine == "periodic" and args.speed not in (1.5, 4.):
            raise ValueError("The frozen periodic PINN inputs are available at 1.5 and 4.0 mm/s")
    if args.device is None:
        args.device = "cpu" if args.smoke or getattr(args, "engine", None) == "periodic" else "cuda"
    if section == 4 and args.engine == "periodic" and args.device != "cpu":
        raise ValueError("The frozen periodic PINN implementation runs on CPU")
    if section == 2 and args.geometry == "periodic" and not args.smoke and args.device != "cuda":
        raise ValueError("Formal periodic simulation uses CUDA")
    if section == 2 and args.geometry == "cf":
        args.fps = args.fps or {113:90, 175:90, 217:180}.get(args.q)
        if not args.fps or args.fps < 1 or (args.frames is not None and args.frames < 3):
            raise ValueError("Supply a positive --fps for a new CF case (and at least three frames)")
    if section == 3:
        if args.input:
            args.input = project_path(args.input)
            if not args.input.is_relative_to(SECTIONS[2]):
                raise ValueError("--input must identify a data-generation case under 02")
        elif args.q not in (113,175,217):
            raise ValueError("New CF case requires --input from 02")


def simulation(out, args):
    import torch
    if args.smoke:
        torch.set_num_threads(2)
    sys.path.insert(0, str(SECTIONS[2] / "source"))
    if args.geometry == "periodic":
        if args.smoke:
            return periodic_sim_smoke(out, args)
        module = importlib.import_module("run_periodic_cuda")
        dest = out / "autodl-tmp"
        if out is not None:
            dest.mkdir(exist_ok=True)
        cmd = ["--speeds-mm-s", str(args.speed), "--data-root", str(dest)]
        if args.seed is not None:
            cmd += ["--seed-base", str(args.seed)]
    else:
        module = importlib.import_module("run_cf_reference_cuda")
        module.FPS = {args.q: args.fps}
        cmd = ["--cases", str(args.q), "--device", args.device, "--output", str(out / "data")]
        if args.smoke:
            cmd.append("--smoke")
        if args.frames is not None:
            cmd += ["--frames", str(args.frames)]
        if args.seed is not None:
            cmd += ["--seed-base", str(args.seed)]
    cwd = sys.argv
    try:
        sys.argv = [module.__file__, *cmd]
        rc = module.main()
        if rc:
            raise RuntimeError(f"Simulation exited with status {rc}")
    finally:
        sys.argv = cwd
    if args.geometry == "cf":
        return bool(read(out / "data/run_manifest.json")["all_complete"])
    return True


def periodic_sim_smoke(out, args):
    from solver import Config
    from cuda_flow import TorchFlow
    config = Config(grid=32, vn_mean_m_s=args.speed * .001, line_density_m2=32/(.01**2),
                    n_particles=8, initial_trapped_particles=2, seed=args.seed or 3719)
    # This small geometry exercises the maintained forward constructor and checkpoint format.
    flow = TorchFlow(config, device=args.device)
    flow.step(1.e-5)
    flow.save_checkpoint(out / "smoke_checkpoint.npz")
    return True


def periodic_pinn(args, out=None):
    # Paths are resolved in the historic sources; only the single-run destination is redirected.
    paths.install_frozen_imports([REPO, SECTIONS[3] / "dependencies", SECTIONS[4] / "dependencies"])
    sys.path.insert(0, str(REPO / "experiments/pinn_twofluid_20261105"))
    e = importlib.import_module("experiment")
    baseline = e.verify_protocol()
    print("BASELINE_VERIFIED", baseline["fingerprint"], flush=True)
    if out is None:
        return True
    e.setup()
    e.OUT = paths.LegacyPath(out)
    budget = 1 if args.smoke else args.budget
    e.STEPS = budget
    e.BUDGETS = (budget,)
    e.VALIDATE_EVERY = 1 if args.smoke else baseline["validation_every"]
    speed = args.speed * .001
    e.run(speed, args.seed, "pinn", args.limit)
    folder = Path(str(e.folder_for(speed, args.seed, "pinn")))
    status = read(folder / "status.json")
    if status["complete"]:
        from .periodic_export import export
        export(e, speed, args.seed, folder / f"budget_{budget}_primary.pt", out / "reconstruction.npz")
    return bool(status["complete"])


def cf_calibrated(args, out=None):
    verify_bundle(CALIBRATED)
    if out is None:
        print("CF217_CALIBRATED_RELEASE_VERIFIED")
        return True
    work = out / "engine"
    cmd = [sys.executable, "-B", str(CALIBRATED / "launch.py"),
           "smoke" if args.smoke else "run", "--output", str(work), "--device", args.device]
    if args.limit is not None:
        cmd += ["--max-new-steps", str(args.limit)]
    subprocess.run(cmd, check=True)
    return (work / "complete.json").is_file() and read(work / "complete.json")["complete"]


def contract(section, args):
    exclude = {"action", "run_id", "resume", "limit"}
    params = {k: v.relative_to(ROOT).as_posix() if isinstance(v, Path) else v
              for k,v in vars(args).items() if k not in exclude}
    input_digests = {}
    if section == 3 and args.input:
        for name in ("configuration.json", "particles/metadata.json", "particles/frame_manifest.json"):
            input_digests[name] = sha(args.input / name)
    if section == 4 and args.engine == "cf":
        parent = run_path(3, args.probability_run) / "engine"
        for name in ("protocol.json", "probability_frozen.json", "acceptance.json"):
            input_digests[name] = sha(parent / name)
    return dict(schema=1, stage=section, run_id=args.run_id, config=params,
                inputs=input_digests, code=code_record(section, getattr(args,"engine",None)))


def main(section, argv=None):
    p = parser(section)
    args = p.parse_args(argv)
    try:
        paths.load_map()
        prepare_args(section, args)
        if args.action == "plan":
            print(json.dumps(dict(stage=section, target=str(run_path(section,args.run_id)) if args.run_id else None,
                                  config=vars(args)), ensure_ascii=False, indent=2, default=str))
            return 0
        if args.action == "verify":
            if section == 4 and args.engine == "periodic":
                periodic_pinn(args)
            elif section == 4 and args.engine == "cf_calibrated":
                cf_calibrated(args)
            elif section == 3 or section == 4:
                print("CF_BASE_RELEASE_VERIFIED",verify_bundle(FULL))
            else:
                print("DATA_GENERATION_CONFIGURATION_VALID")
            return 0
        if args.device == "cuda":
            import torch
            if not torch.cuda.is_available():
                raise ValueError("CUDA unavailable; use --smoke --device cpu for diagnostics")
        if args.device == "cpu" and not args.smoke and getattr(args,"engine",None)!="periodic":
            raise ValueError("Use CUDA for formal runs, or --smoke for CPU diagnostics")
        out = run_path(section, args.run_id)
        spec = contract(section,args)
        with writable_run(out,spec,args.resume):
            complete = out / "status.json"
            if complete.is_file() and read(complete).get("complete"):
                print("RUN_ALREADY_COMPLETE",out)
                return 0
            if section == 2:
                done = simulation(out,args)
            elif section == 4 and args.engine == "periodic":
                done = periodic_pinn(args,out)
            elif section == 4 and args.engine == "cf_calibrated":
                done = cf_calibrated(args,out)
            else:
                from .cf_run import probability, reconstruct
                done = probability(args,out) if section == 3 else reconstruct(args,out)
            save(complete,dict(complete=bool(done),action=args.action,diagnostic_only=args.smoke))
            print("RUN_COMPLETE" if done else "RUN_SAVED_OR_PREPARED",out)
        return 0
    except (ValueError, FileExistsError) as exc:
        p.error(str(exc))
